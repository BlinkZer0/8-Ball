# ============================================================================
#  Builds web/index.html: ONE self-contained file with the UI (vst/ui), the
#  engine compiled to WebAssembly (webhost/wasm-engine.cpp + Source/dsp, via
#  Emscripten), the web host (webhost/web-host.js) and the factory presets.
#  Usage: powershell -ExecutionPolicy Bypass -File vst\webhost\build-web.ps1 [-SkipWasm]
#  Emscripten: %LOCALAPPDATA%\EightBallVST\emsdk (install: git clone emsdk, emsdk install latest,
#  emsdk activate latest) or EMSDK in the environment. -SkipWasm reuses the last .wasm.
# ============================================================================
param([switch]$SkipWasm)
$ErrorActionPreference = 'Stop'
$vst  = Split-Path $PSScriptRoot -Parent
$repo = Split-Path $vst -Parent
$ui   = Join-Path $vst 'ui'
$out  = Join-Path $repo 'web\index.html'
$work = Join-Path $env:LOCALAPPDATA 'EightBallVST\wasm'
$wasm = Join-Path $work 'eight-ball.wasm'
$utf8 = [Text.UTF8Encoding]::new($false)
$read = { param($path) [IO.File]::ReadAllText($path, $utf8) }
$version = (Select-String -Path (Join-Path $vst 'CMakeLists.txt') -Pattern 'project\(EightBallVST VERSION ([0-9.]+)').Matches[0].Groups[1].Value

# ---- 1. the engine -> WebAssembly ------------------------------------------------------------
if (-not $SkipWasm -or -not (Test-Path $wasm)) {
    $sdk = if ($env:EMSDK) { $env:EMSDK } else { Join-Path $env:LOCALAPPDATA 'EightBallVST\emsdk' }
    if (-not (Test-Path (Join-Path $sdk 'upstream\emscripten\emcc.py'))) { throw "Emscripten not found at $sdk (see the header of this script)" }
    $node = Get-ChildItem (Join-Path $sdk 'node') | Select-Object -First 1
    $env:EMSDK = $sdk
    $env:PATH = "$sdk;$sdk\upstream\emscripten;$($node.FullName)\bin;$env:PATH"
    New-Item -ItemType Directory -Force $work | Out-Null
    $src = Join-Path $PSScriptRoot 'wasm-engine.cpp'
    $exports = (Select-String -Path $src -Pattern 'EB_EXPORT \S+ (eb_\w+)' -AllMatches).Matches | ForEach-Object { '_' + $_.Groups[1].Value }
    $exports += '_malloc', '_free'
    Write-Host "[Eight Ball] em++ ($($exports.Count) exports)..."
    & em++ $src -O3 -std=c++17 "-I$(Join-Path $vst 'Source')" -fno-exceptions -fno-rtti `
        -s STANDALONE_WASM=1 --no-entry -s INITIAL_MEMORY=33554432 -s ALLOW_MEMORY_GROWTH=1 `
        -s EXPORTED_FUNCTIONS="[$($exports -join ',')]" -o $wasm
    if ($LASTEXITCODE -ne 0) { throw "em++ failed" }
}
$wasmB64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($wasm))
Write-Host ("[Eight Ball] wasm {0:N0} KB" -f ((Get-Item $wasm).Length / 1KB))

# ---- 2. the page --------------------------------------------------------------------------------
$html = & $read (Join-Path $ui 'index.html')
function Script([string]$code) {
    if ($code -match '</script') { throw 'inlined code must not contain </script' }
    return "<script>`n$code`n</script>"
}
$css = & $read (Join-Path $ui 'css\style.css')
$html = $html.Replace('<link rel="stylesheet" href="css/style.css">', "<style>`n$css`n</style>")

# the web host, the wasm and the factory presets go in before the bridge (engine-juce.js) is constructed
$presets = (& $read (Join-Path $vst 'presets\factory_presets.json')).Trim()
$hostScripts = @(
    (Script ("// the engine, compiled to WebAssembly from vst/Source (vst/webhost/wasm-engine.cpp)`nconst EIGHTBALL_WASM_B64 = '" + $wasmB64 + "';")),
    (Script ("// the factory presets (vst/presets/factory_presets.json, generated by make_presets.py)`nconst FACTORY_JSON = " + $presets + ';')),
    (Script (& $read (Join-Path $PSScriptRoot 'web-host.js')))
) -join "`n"
$html = [regex]::Replace($html, '<script src="js/([\w.-]+)"></script>', {
    param($m)
    $name = $m.Groups[1].Value
    $code = Script (& $read (Join-Path $ui "js\$name"))
    if ($name -eq 'engine-juce.js') { return "$hostScripts`n$code" }
    return $code
})
if ($html -match 'src="js/') { throw 'a script was not inlined' }
$icon = [Convert]::ToBase64String([IO.File]::ReadAllBytes((Join-Path $vst 'icon\eight-ball-32.png')))
$html = $html.Replace('<title>Eight Ball</title>', "<title>Eight Ball v$version</title>`n  <link rel=`"icon`" type=`"image/png`" href=`"data:image/png;base64,$icon`">")
$banner = @"
<!--
  Eight Ball v$version - web build. ONE self-contained file: the UI, the engine as WebAssembly (the same C++ the
  VST3 runs) and the 1000+ factory presets. GENERATED by vst/webhost/build-web.ps1 from vst/ui, vst/Source and
  vst/webhost: edit those, not this file. Open in Chrome or Edge (Web MIDI); start.bat serves it for the
  AudioWorklet path (from disk it falls back to a ScriptProcessor).
-->
"@
$html = $html.Replace('<!doctype html>', "<!doctype html>`n$banner")

New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
[IO.File]::WriteAllText($out, $html, $utf8)
Write-Host ("[Eight Ball] wrote {0} ({1:N0} KB)" -f $out, ((Get-Item $out).Length / 1KB))
# GitHub Pages serves docs/: keep the live copy in step
$pages = Join-Path $repo 'docs\index.html'
[IO.File]::WriteAllText($pages, $html, $utf8)
Write-Host "[Eight Ball] wrote $pages (GitHub Pages)"
